/* ---------- 日志 ---------- */
function classifyLog(msg) {
  if (/❌|失败|异常|error/i.test(msg)) return "err";
  if (/✅|成功|完成/.test(msg)) return "ok";
  if (/⚠️|警告/.test(msg)) return "warn";
  if (/🚀|⏺️|📶|🔄|命令|启动/.test(msg)) return "cmd";
  return "";
}

async function pollLogs() {
  const r = await api("/api/logs?since=" + S.lastLogSeq);
  if (!r.ok || !r.logs.length) return;
  const view = $("logView");
  const stick = view.scrollTop + view.clientHeight >= view.scrollHeight - 20;
  r.logs.forEach(e => {
    S.lastLogSeq = Math.max(S.lastLogSeq, e.seq);
    const line = document.createElement("div");
    line.className = "log-line " + classifyLog(e.msg);
    line.innerHTML = `<span class="log-time">${e.time}</span><span class="log-msg"></span>`;
    line.querySelector(".log-msg").textContent = e.msg;
    view.appendChild(line);
  });
  // 限制 DOM 行数
  while (view.children.length > 500) view.firstElementChild.remove();
  if (stick) view.scrollTop = view.scrollHeight;
}
setInterval(pollLogs, 1000);

