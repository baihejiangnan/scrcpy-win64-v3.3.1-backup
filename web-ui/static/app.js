/* ---------- 状态轮询 ---------- */
async function pollState() {
  const r = await api("/api/state");
  if (!r.ok) return r;
  S.mirroring = r.mirroring;
  S.recording = r.recording;
  S.mirrorElapsed = r.mirrorElapsed || 0;
  S.recordElapsed = r.recordElapsed || 0;
  S.polledAt = Date.now();
  // 若后端选择的设备与本地不一致（如重连），以后端为准
  if (r.selected && r.selected !== S.selected) {
    S.selected = r.selected;
    S.deviceKey = "";
  }
  // 选中设备掉线时清除选择
  if (S.selected && !r.devices.find(d => d.id === S.selected)) {
    S.selected = "";
    S.selectedModel = "";
    S.deviceKey = "";
  }
  const cur = r.devices.find(d => d.id === S.selected);
  S.selectedModel = cur && cur.model ? cur.model : "";
  renderDevices(r.devices);
  refreshHero();
  refreshPreview();
  refreshStatusChip(r.devices);
  renderRecordBtn(r.recordFile);
  renderFiles(r.recordings || []);
  return r;
}
setInterval(pollState, 2500);

