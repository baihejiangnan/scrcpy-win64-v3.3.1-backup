const BG = {
  KEY_ON: "scrcpy-bg-on",
  KEY_AUTO: "scrcpy-bg-auto",
  KEY_IDX: "scrcpy-bg-idx",
  INTERVAL: 30000,
  list: [], idx: 0, timer: null, front: null, auto: true, failCount: 0,
};
function bgStore(k, v) { try { localStorage.setItem(k, v); } catch (_) {} }
function bgRead(k) { try { return localStorage.getItem(k); } catch (_) { return null; } }

function fallbackWallpapers() {
  // 无本地壁纸时的在线图源（picsum 固定种子，列表稳定可缓存）
  const seeds = ["aurora", "valley", "neon", "forest", "ocean", "city", "dusk", "mountain"];
  return seeds.map(s => `https://picsum.photos/seed/scrcpy-${s}/1920/1080`);
}
async function loadWallpaperList() {
  try {
    const r = await fetch("/api/wallpapers");
    const j = await r.json();
    if (j.ok && j.wallpapers.length) {
      return j.wallpapers.map(n => "/wallpapers/" + encodeURIComponent(n));
    }
  } catch (_) {}
  return fallbackWallpapers();
}
function preload(src) {
  return new Promise((res, rej) => {
    const im = new Image();
    im.onload = () => res(src);
    im.onerror = rej;
    im.src = src;
  });
}
function applyBg(on) {
  document.body.classList.toggle("has-wallpaper", on);
  bgStore(BG.KEY_ON, on ? "1" : "0");
  $("btnBgOff").classList.toggle("off", !on);
}
async function showBg(i, animate = true) {
  if (!BG.list.length) return;
  BG.idx = ((i % BG.list.length) + BG.list.length) % BG.list.length;
  bgStore(BG.KEY_IDX, String(BG.idx));
  const a = $("bgA"), b = $("bgB");
  const back = BG.front === a ? b : a;
  try {
    await preload(BG.list[BG.idx]);
  } catch (_) {
    // 加载失败自动跳下一张，全部失败则放弃
    BG.failCount += 1;
    if (BG.failCount < BG.list.length) return showBg(BG.idx + 1, animate);
    return;
  }
  BG.failCount = 0;
  back.style.backgroundImage = `url("${BG.list[BG.idx]}")`;
  if (!animate) back.style.transition = "none";
  back.classList.add("show");
  if (BG.front) BG.front.classList.remove("show");
  if (!animate) requestAnimationFrame(() => { back.style.transition = ""; });
  BG.front = back;
  applyBg(true);
}
function bgSetAuto(on) {
  BG.auto = on;
  bgStore(BG.KEY_AUTO, on ? "1" : "0");
  clearInterval(BG.timer);
  BG.timer = null;
  if (on) BG.timer = setInterval(() => showBg(BG.idx + 1), BG.INTERVAL);
  $("bgToggleIcon").innerHTML = on ? ICONS.pause : ICONS.play;
  $("btnBgToggle").title = on ? "暂停自动轮换" : "开启自动轮换";
}
async function initBackground() {
  BG.list = await loadWallpaperList();
  if (!BG.list.length) return;
  const on = bgRead(BG.KEY_ON) !== "0";      // 默认开启
  const auto = bgRead(BG.KEY_AUTO) !== "0";  // 默认自动轮换
  const saved = parseInt(bgRead(BG.KEY_IDX) || "", 10);
  BG.idx = Number.isFinite(saved) ? saved : Math.floor(Math.random() * BG.list.length);
  $("btnBgPrev").onclick = () => showBg(BG.idx - 1);
  $("btnBgNext").onclick = () => showBg(BG.idx + 1);
  $("btnBgToggle").onclick = () => bgSetAuto(!BG.auto);
  $("btnBgOff").onclick = () => {
    const turningOff = document.body.classList.contains("has-wallpaper");
    applyBg(!turningOff);
    if (turningOff) {
      clearInterval(BG.timer); BG.timer = null;  // 暂停但不覆盖用户的自动偏好
    } else {
      if (!BG.front) showBg(BG.idx, false);
      bgSetAuto(bgRead(BG.KEY_AUTO) !== "0");
    }
  };
  bgSetAuto(auto);
  if (on) showBg(BG.idx, false); else applyBg(false);
}
initBackground();

