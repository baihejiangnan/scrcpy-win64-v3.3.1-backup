const SIZE_MAP = { "720": "1280", "1080": "1920", "1440": "2560", "2160": "3840" };
const FLAGS = ["showTouches", "stayAwake", "noAudio", "turnScreenOff",
               "alwaysOnTop", "fullscreen", "noControl", "disableScreensaver"];
const FLAG_ARGS = {
  showTouches: "--show-touches", stayAwake: "--stay-awake", noAudio: "--no-audio",
  turnScreenOff: "--turn-screen-off", alwaysOnTop: "--always-on-top",
  fullscreen: "--fullscreen", noControl: "--no-control",
  disableScreensaver: "--disable-screensaver",
};

function collectParams() {
  const flags = {};
  FLAGS.forEach(f => {
    const el = document.querySelector(`.toggle[data-flag="${f}"]`);
    flags[f] = el && el.dataset.on === "true";
  });
  return {
    rotation: $("selRotation").value,
    fps: $("selFps").value,
    bitrate: $("selBitrate").value,
    resolution: $("selResolution").value,
    flags,
  };
}

function buildPreview() {
  const p = collectParams();
  const parts = ["scrcpy.exe", "--serial", S.selected || "<设备>"];
  if (p.rotation !== "0") parts.push("--orientation", p.rotation);
  if (p.fps) parts.push("--max-fps", p.fps);
  if (p.bitrate) parts.push("--video-bit-rate", p.bitrate);
  if (p.resolution && SIZE_MAP[p.resolution]) parts.push("--max-size", SIZE_MAP[p.resolution]);
  FLAGS.forEach(f => { if (p.flags[f]) parts.push(FLAG_ARGS[f]); });
  return parts.join(" ");
}

function refreshPreview() { $("cmdText").textContent = buildPreview(); }

