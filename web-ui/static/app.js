async function uploadFile(file) {
  if (!S.selected) return toast("caution", "请先选择设备");
  const isApk = file.name.toLowerCase().endsWith(".apk");
  const url = isApk
    ? "/api/apk/install?name=" + encodeURIComponent(file.name)
    : "/api/file/push?name=" + encodeURIComponent(file.name) + "&dest=" + encodeURIComponent("/sdcard/Download/");
  const t = toast("loading", (isApk ? "正在安装 " : "正在推送 ") + file.name + " …");
  try {
    const res = await fetch(url, { method: "PUT", body: file });
    const r = await res.json();
    dismissToast(t);
    r.ok ? toast("success", isApk ? "APK 安装成功" : "文件已推送")
         : toast("error", r.error || r.output || "操作失败");
  } catch (e) {
    dismissToast(t);
    toast("error", "上传失败: " + e.message);
  }
}

